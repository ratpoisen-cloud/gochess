/**
 * Данные дебютов: единый источник для тренажёра (/bot/openings), справочника
 * и открывающей книги Ичи (src/lib/bot/openingBook.ts).
 *
 * Линии хранятся в SAN — их читает и правит человек. UCI-эквивалент
 * вычисляется движком (см. src/lib/openings.ts), поэтому опечатка в линии
 * сразу всплывает в тестах, а не в игре.
 */

export type OpeningFamily = 'open' | 'semi-open' | 'closed' | 'irregular'
export type OpeningDifficulty = 'easy' | 'medium' | 'hard'
export type OpeningColor = 'w' | 'b'

export interface OpeningStep {
  /** Ход в алгебраической нотации, без номера: 'e4', 'Nf3', 'O-O'. */
  san: string
  /** Пояснение к ходу: что он делает и зачем. */
  comment: string
}

export interface OpeningDeviation {
  /** Индекс шага в steps[], на котором игрок обычно отклоняется от теории. */
  at: number
  /** Типичная ошибка вместо шага steps[at]. */
  san: string
  /** Почему так делать не надо. */
  comment: string
}

export interface Opening {
  id: string
  name: string
  eco: string
  family: OpeningFamily
  /** За кого играет игрок в тренажёре. */
  color: OpeningColor
  difficulty: OpeningDifficulty
  /** Короткое описание дебюта: зачем он нужен. */
  summary: string
  /** Ключевая идея дебюта одной фразой. */
  idea: string
  /** Главная линия с комментариями. */
  steps: OpeningStep[]
  /** Типичные отклонения новичков. */
  deviations: OpeningDeviation[]
}

